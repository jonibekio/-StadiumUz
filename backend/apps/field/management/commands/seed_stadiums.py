class Command(BaseCommand):
    help = 'Seed real Uzbekistan stadium data with images'

    def add_arguments(self, parser):
        parser.add_argument(
            '--clear',
            action='store_true',
            help='Clear existing stadiums before seeding',
        )

    def handle(self, *args, **options):
        if options['clear']:
            Stadium.objects.all().delete()
            self.stdout.write(self.style.WARNING('All existing stadiums cleared'))

        created_count = 0
        updated_count = 0

        for data in STADIUMS:
            features = data.pop('features', [])
            stadium, created = Stadium.objects.update_or_create(
                name=data['name'],
                defaults=data,
            )
            if created:
                created_count += 1
                self.stdout.write(self.style.SUCCESS(f'Created: {stadium.name} ({stadium.region})'))
            else:
                updated_count += 1
                self.stdout.write(self.style.WARNING(f'Updated: {stadium.name}'))

            # Update features
            stadium.features.all().delete()
            for feature_name in features:
                StadiumFeature.objects.create(stadium=stadium, name=feature_name)

        self.stdout.write(self.style.SUCCESS(
            f'\nDone! Created: {created_count}, Updated: {updated_count}, Total: {created_count + updated_count}'
        ))
